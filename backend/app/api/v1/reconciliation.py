"""Reconciliation API: statement ingestion, runs, results, and exception drill-down."""
import uuid
from datetime import datetime, timezone
from typing import Optional, List, Dict, Any

from fastapi import APIRouter, Depends, HTTPException, UploadFile, File, Form, status
from pydantic import BaseModel
from sqlalchemy import select, desc
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.v1.auth import get_current_user, require_roles
from app.db.database import get_db
from app.models import (
    User, UserRole, ReconRun, ReconFile, ReconItem, ExceptionCase,
    ExceptionStatus, Payment, PaymentState
)
from app.services.audit_service import record_audit_log
from app.services.payment_service import transition_payment_state
from app.services.recon_service import (
    parse_csv_statement, parse_camt_053_statement, run_reconciliation
)

router = APIRouter(prefix="/reconciliation", tags=["reconciliation"])


class ResolveExceptionRequest(BaseModel):
    resolution_action: str  # e.g., "FORCE_SETTLE", "CANCEL_INTERNAL", "IGNORE"
    notes: Optional[str] = None


@router.get("/runs")
async def list_recon_runs(
    limit: int = 50,
    offset: int = 0,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """List historical reconciliation runs."""
    stmt = select(ReconRun).order_by(desc(ReconRun.created_at)).limit(limit).offset(offset)
    res = await db.execute(stmt)
    return res.scalars().all()


@router.get("/runs/{run_id}")
async def get_recon_run(
    run_id: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Get statistics and details of a single reconciliation run."""
    stmt = select(ReconRun).where(ReconRun.id == run_id)
    res = await db.execute(stmt)
    run = res.scalar_one_or_none()
    if not run:
        raise HTTPException(status_code=404, detail="Reconciliation run not found")
    return run


@router.get("/runs/{run_id}/exceptions")
async def get_run_exceptions(
    run_id: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Get all exceptions generated by a specific reconciliation run."""
    stmt = select(ExceptionCase).where(ExceptionCase.recon_run_id == run_id).order_by(desc(ExceptionCase.created_at))
    res = await db.execute(stmt)
    return res.scalars().all()


@router.post("/upload-and-run")
async def upload_statement_and_run(
    rail_code: str = Form("UPI"),
    auto_resolve: bool = Form(True),
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_roles([UserRole.OPERATIONS, UserRole.ADMIN]))
):
    """Uploads a statement file (CSV or camt.053 XML) and immediately executes reconciliation."""
    file_bytes = await file.read()
    content_str = file_bytes.decode("utf-8", errors="replace")

    # Parse statement file
    if file.filename.endswith(".xml") or "<Document" in content_str:
        records = parse_camt_053_statement(content_str)
        file_format = "CAMT_053_XML"
    else:
        records = parse_csv_statement(content_str)
        file_format = "CSV"

    if not records:
        raise HTTPException(status_code=400, detail="Could not parse any statement records from file")

    run_id = str(uuid.uuid4())
    now = datetime.now(timezone.utc)

    recon_run = ReconRun(
        id=run_id,
        rail=rail_code.upper(),
        status="RUNNING",
        total_records=len(records),
        created_at=now
    )
    db.add(recon_run)

    recon_file = ReconFile(
        id=str(uuid.uuid4()),
        recon_run_id=run_id,
        filename=file.filename,
        file_format=file_format,
        file_size_bytes=len(file_bytes),
        records_count=len(records),
        created_at=now
    )
    db.add(recon_file)
    await db.commit()

    # Execute reconciliation pipeline
    results = await run_reconciliation(
        db=db,
        recon_run_id=run_id,
        rail_code=rail_code,
        statement_records=records,
        auto_resolve=auto_resolve,
        actor_id=current_user.id
    )
    await db.commit()

    return results


@router.post("/exceptions/{exception_id}/resolve")
async def resolve_recon_exception(
    exception_id: str,
    payload: ResolveExceptionRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_roles([UserRole.OPERATIONS, UserRole.ADMIN]))
):
    """Resolves an exception case with a chosen action."""
    stmt = select(ExceptionCase).where(ExceptionCase.id == exception_id)
    res = await db.execute(stmt)
    case = res.scalar_one_or_none()
    if not case:
        raise HTTPException(status_code=404, detail="Exception case not found")

    case.status = ExceptionStatus.RESOLVED
    case.resolution_notes = f"Action: {payload.resolution_action}. Notes: {payload.notes or ''}"
    case.assigned_to = current_user.id
    case.resolved_at = datetime.now(timezone.utc)

    # Perform action on underlying payment if applicable
    if case.payment_id and payload.resolution_action == "FORCE_SETTLE":
        p_stmt = select(Payment).where(Payment.id == case.payment_id)
        p_res = await db.execute(p_stmt)
        p = p_res.scalar_one_or_none()
        if p and p.state in (PaymentState.SUBMITTED, PaymentState.AUTHORISED):
            await transition_payment_state(
                db, p, PaymentState.SETTLED,
                actor=current_user.email,
                reason=f"Manual exception resolution: {payload.resolution_action}"
            )

    await db.commit()

    await record_audit_log(
        db=db,
        entity_type="EXCEPTION_CASE",
        entity_id=case.id,
        action="RESOLVE",
        actor_id=current_user.id,
        actor_type="USER",
        new_values={"resolution_action": payload.resolution_action, "notes": payload.notes}
    )

    return {"message": "Exception resolved", "exception_id": case.id, "status": "RESOLVED"}
